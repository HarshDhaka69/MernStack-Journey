// Switch Condition

// In switch, strict equality (===) is used for comparison.

let marks = 90;

switch (marks) {
    case 90:
        console.log("A+");
        break;

    case 80:
        console.log("A");
        break;

    case 70:
        console.log("B");
        break;

    case 60:
        console.log("C");
        break;

    default:
        console.log("Try To Improve Yourself");
        break;
}